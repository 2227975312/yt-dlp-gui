//! Netscape cookies.txt 文本的校验、规范化与域名派生
//!
//! 用户手动粘贴的文本可能来自各种渠道（浏览器导出、插件、手工整理），
//! 这里统一做一次严格校验后落库，避免把非法内容交给 yt-dlp。

use std::collections::BTreeSet;

/// 单份 cookie 文本的体积上限
const MAX_CONTENT_BYTES: usize = 2 * 1024 * 1024;
/// 单份 cookie 文本允许的最大 cookie 行数
const MAX_COOKIE_LINES: usize = 5000;

/// 解析结果
#[derive(Debug)]
pub struct ParsedCookieFile {
    /// 统一以 `\n` 结尾的规范化文本
    pub normalized: String,
    /// 从 cookie 域名列派生的匹配规则（已去重升序）
    pub domains: Vec<String>,
    /// 有效 cookie 行数
    pub cookie_count: usize,
}

/// 校验并规范化 cookie 文本
pub fn parse(text: &str) -> Result<ParsedCookieFile, String> {
    if text.len() > MAX_CONTENT_BYTES {
        return Err("err_cookie_too_large".into());
    }

    let mut lines: Vec<String> = Vec::new();
    let mut domains: BTreeSet<String> = BTreeSet::new();
    let mut has_header = false;
    let mut cookie_count = 0usize;

    for (index, raw) in text.lines().enumerate() {
        let line = raw.trim_end_matches('\r');
        if index == 0 && matches!(line, "# Netscape HTTP Cookie File" | "# HTTP Cookie File") {
            has_header = true;
        }
        // 注释（含 #HttpOnly_ 例外）与空行原样保留
        if line.is_empty() || (line.starts_with('#') && !line.starts_with("#HttpOnly_")) {
            lines.push(line.to_string());
            continue;
        }

        let fields: Vec<&str> = line.split('\t').collect();
        if fields.len() != 7
            || fields[0].is_empty()
            || !matches!(fields[1], "TRUE" | "FALSE")
            || !fields[2].starts_with('/')
            || !matches!(fields[3], "TRUE" | "FALSE")
            || fields[4].parse::<i64>().is_err()
            || fields[5].is_empty()
        {
            return Err(format!("err_invalid_cookie_line:{}", index + 1));
        }

        cookie_count += 1;
        if cookie_count > MAX_COOKIE_LINES {
            return Err("err_too_many_cookies".into());
        }

        if let Some(domain) = derive_domain(fields[0]) {
            domains.insert(domain);
        }
        lines.push(line.to_string());
    }

    if !has_header {
        return Err("err_invalid_cookie_header".into());
    }
    if cookie_count == 0 {
        return Err("err_empty_cookie_file".into());
    }

    Ok(ParsedCookieFile {
        normalized: format!("{}\n", lines.join("\n")),
        domains: domains.into_iter().collect(),
        cookie_count,
    })
}

/// 从 cookie 域名列派生匹配规则
///
/// 证书域写作 `.example.com` 表示覆盖所有子域，去掉前导点后正好是后缀规则的语义；
/// `www.` 前缀同样属于站点别名，一并去掉以便一条规则同时覆盖主域与子域。
fn derive_domain(raw: &str) -> Option<String> {
    let host = raw
        .trim()
        .trim_start_matches("#HttpOnly_")
        .trim_start_matches('.');
    let host = host.trim_end_matches('.').to_ascii_lowercase();
    if host.is_empty() || host.contains(char::is_whitespace) {
        return None;
    }
    Some(host.strip_prefix("www.").unwrap_or(&host).to_string())
}

#[cfg(test)]
mod tests {
    use super::parse;

    const HEADER: &str = "# Netscape HTTP Cookie File";

    fn line(domain: &str, name: &str) -> String {
        format!("{domain}\tTRUE\t/\tFALSE\t1893456000\t{name}\tvalue")
    }

    #[test]
    fn accepts_and_normalizes_crlf_content() {
        let text = format!(
            "{HEADER}\r\n{}\r\n{}\r\n",
            line(".example.com", "a"),
            line("www.example.com", "b")
        );
        let parsed = parse(&text).expect("valid cookie file");
        assert_eq!(parsed.cookie_count, 2);
        assert_eq!(parsed.domains, vec!["example.com".to_string()]);
        assert!(parsed.normalized.ends_with('\n'));
        assert!(!parsed.normalized.contains('\r'));
    }

    #[test]
    fn derives_domains_without_www_and_leading_dot() {
        let text = format!(
            "{HEADER}\n{}\n{}\n{}\n",
            line(".google.com", "a"),
            line("#HttpOnly_.youtube.com", "b"),
            line("api.bilibili.com", "c")
        );
        let parsed = parse(&text).expect("valid cookie file");
        assert_eq!(
            parsed.domains,
            vec![
                "api.bilibili.com".to_string(),
                "google.com".to_string(),
                "youtube.com".to_string()
            ]
        );
    }

    #[test]
    fn accepts_cookie_editor_export_with_comment_lines() {
        // Cookie-Editor 导出的文件带有若干 http:// 开头的注释行，必须原样接受
        let text = concat!(
            "# Netscape HTTP Cookie File\n",
            "# http://curl.haxx.se/rfc/cookie_spec.html\n",
            "# This file was generated by Cookie-Editor\n",
            ".bilibili.com\tTRUE\t/\tFALSE\t1796906584\tCURRENT_QUALITY\t127\n"
        );
        let parsed = parse(text).expect("valid cookie file");
        assert_eq!(parsed.cookie_count, 1);
        assert_eq!(parsed.domains, vec!["bilibili.com".to_string()]);
        assert!(parsed
            .normalized
            .starts_with("# Netscape HTTP Cookie File\n# http://"));
    }

    #[test]
    fn rejects_missing_header() {
        let text = format!("{}\n", line(".example.com", "a"));
        assert_eq!(parse(&text).unwrap_err(), "err_invalid_cookie_header");
    }

    #[test]
    fn rejects_empty_and_invalid_lines() {
        assert_eq!(parse(HEADER).unwrap_err(), "err_empty_cookie_file");
        let text = format!(
            "{HEADER}\n{}\n",
            line(".example.com", "a").replace('\t', " ")
        );
        assert_eq!(parse(&text).unwrap_err(), "err_invalid_cookie_line:2");
    }
}
